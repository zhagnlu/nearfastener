import { execFileSync } from 'node:child_process';
import { writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { siteOrigin } from './seo.mjs';
import site from '../content/site.json' with { type: 'json' };

const root = fileURLToPath(new URL('../', import.meta.url));
const git = (args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
const marker = join(root, 'static-site/.ecs-build.json');
const origin = siteOrigin(site);
const allowUnconfiguredOrigin = process.argv.includes('--allow-unconfigured-origin');
if (!origin && !allowUnconfiguredOrigin) throw new Error('Set the confirmed production HTTPS domain in content/site.json before building a release, or explicitly use --allow-unconfigured-origin to publish without domain-dependent SEO metadata.');
if (!origin) console.warn('Publishing without a configured origin: canonical, hreflang and sitemap remain pending.');
rmSync(marker, { force: true });
if (git(['status', '--porcelain'])) throw new Error('Commit development changes before building the ECS publication.');
if (git(['branch', '--show-current']) === 'push_remote') throw new Error('Build from the development branch.');
execFileSync('npm', ['test'], { cwd: root, stdio: 'inherit' });
if (git(['status', '--porcelain'])) throw new Error('Build updated generated files. Commit them, then run build:ecs again.');
writeFileSync(marker, JSON.stringify({ sourceCommit: git(['rev-parse', 'HEAD']), builtAt: new Date().toISOString(), origin, domainSeoPending: !origin }) + '\n');
console.log('ECS build ready in static-site/. Preview it, then run npm run publish:ecs. Nothing pushed.');
